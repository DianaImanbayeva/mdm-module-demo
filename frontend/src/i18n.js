export function translate(lang, key) {
  return (dict[lang] && dict[lang][key]) || dict.ru[key] || key;
}

// Простая интерполяция плейсхолдеров вида "{name}" в переведённой строке.
export function format(str, params) {
  return String(str).replace(/\{(\w+)\}/g, (_, k) => (params && params[k] != null ? params[k] : `{${k}}`));
}

// Часть переводов в erp.localization (особенно у таблицы "resources") — по сути
// сырой машинный перевод с артефактами: слова через точку без пробелов
// ("Dusbin.service", "Rent.manager.accomadation"). Показывать такое в интерфейсе
// хуже, чем оставить русский — таблица ru всегда чистая (источник истины),
// поэтому для явно битых строк откатываемся на неё.
function looksMalformed(s) {
  if (!s) return true;
  return !/\s/.test(s) && /[a-zA-Zа-яА-Я0-9]\.[a-zA-Zа-яА-Я]/.test(s);
}

// name — исходное нормализованное имя (fallback), translations — {ru,en,ka,az}
export function pickTranslatedName(name, translations, lang) {
  const candidate = translations && translations[lang];
  if (candidate && !looksMalformed(candidate)) return candidate;
  const ru = translations && translations.ru;
  if (ru && !looksMalformed(ru)) return ru;
  const s = String(name || '');
  return s.charAt(0).toUpperCase() + s.slice(1);
}

